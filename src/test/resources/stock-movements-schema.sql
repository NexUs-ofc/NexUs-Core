CREATE SCHEMA IF NOT EXISTS bi_hist;
CREATE TABLE profile (
    id INTEGER PRIMARY KEY,
    address_id INTEGER,
    email VARCHAR(255),
    name VARCHAR(150),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    type VARCHAR(30),
    profile_image_url VARCHAR(500),
    status VARCHAR(30),
    dietary_restrictions VARCHAR ARRAY
);
CREATE TABLE food (
    id INTEGER PRIMARY KEY,
    name VARCHAR(150),
    category_id INTEGER,
    product_brand VARCHAR(100),
    food_image_url VARCHAR(500),
    package_quantity NUMERIC(10,2),
    unit_of_measure VARCHAR(30),
    gtin VARCHAR(14)
);
CREATE TABLE category (id INTEGER PRIMARY KEY, category_name VARCHAR(100));
CREATE TABLE address (
    id INTEGER PRIMARY KEY,
    neighborhood VARCHAR(100),
    street VARCHAR(150),
    number VARCHAR(10),
    cep CHAR(8),
    city VARCHAR(100),
    state CHAR(2),
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6)
);
CREATE TABLE pantry_item (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_id INTEGER NOT NULL REFERENCES food(id),
    profile_id INTEGER NOT NULL REFERENCES profile(id),
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    expiry_date DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE bi_hist.registro_estoque (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pantry_item_id INTEGER NOT NULL REFERENCES public.pantry_item(id),
    event_type VARCHAR(30) NOT NULL CHECK (event_type IN ('CONSUMED', 'DISCARDED')),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    event_date TIMESTAMP NOT NULL
);
