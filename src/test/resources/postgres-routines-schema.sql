CREATE TABLE profile (
    id INTEGER PRIMARY KEY,
    address_id INTEGER,
    email VARCHAR(255),
    name VARCHAR(150),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    type VARCHAR(30),
    profile_image_url VARCHAR(500),
    status VARCHAR(30),
    dietary_restrictions TEXT[]
);
CREATE TABLE food (
    id INTEGER PRIMARY KEY,
    name VARCHAR(150),
    category_id INTEGER,
    product_brand VARCHAR(100),
    food_image_url VARCHAR(500),
    package_quantity NUMERIC(10,2),
    unit_of_measure VARCHAR(30),
    gtin VARCHAR(14)
);
CREATE TABLE category (id INTEGER PRIMARY KEY, category_name VARCHAR(100));
CREATE TABLE address (
    id INTEGER PRIMARY KEY,
    neighborhood VARCHAR(100),
    street VARCHAR(150),
    number VARCHAR(10),
    cep CHAR(8),
    city VARCHAR(100),
    state CHAR(2),
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6)
);
CREATE TABLE pantry_item (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_id INTEGER NOT NULL REFERENCES food(id),
    profile_id INTEGER NOT NULL REFERENCES profile(id),
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    expiry_date DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE pantry_product_setting (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id INTEGER NOT NULL REFERENCES profile(id),
    food_id INTEGER NOT NULL REFERENCES food(id),
    minimum_quantity INTEGER NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (profile_id, food_id)
);
CREATE TABLE plan (id INTEGER PRIMARY KEY, plan_price NUMERIC(10,2) NOT NULL);
CREATE TABLE company (id INTEGER PRIMARY KEY, profile_id INTEGER REFERENCES profile(id), plan_id INTEGER REFERENCES plan(id));
CREATE TABLE store (id INTEGER PRIMARY KEY, company_id INTEGER REFERENCES company(id), profile_id INTEGER REFERENCES profile(id));
CREATE TABLE payment (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    due_date DATE,
    billing_period_start DATE,
    billing_period_end DATE,
    payment_status VARCHAR(30),
    company_id INTEGER REFERENCES company(id),
    plan_id INTEGER REFERENCES plan(id),
    amount NUMERIC(10,2),
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (company_id, billing_period_start)
);
